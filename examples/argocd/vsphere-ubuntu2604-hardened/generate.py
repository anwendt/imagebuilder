#!/usr/bin/env python3
"""Generates scripts/70-system-role.sh and the VMImage manifest from the
sources in this directory. The VMImage carries every provisioner inline because
the vSphere remote build supports shell and file provisioners only.

Usage: generate.py [--proxy URL] [--admin-user NAME] [--provider-config NAME]
                   [--image-name NAME] [--out FILE]
"""
import argparse
import os

here = os.path.dirname(os.path.abspath(__file__))
SOURCE_URL = "https://cloud-images.ubuntu.com/releases/resolute/release-20261016/ubuntu-26.04-server-cloudimg-amd64.ova"
SOURCE_SHA256 = "fb52eeb79c0e71bce675729a7d67f5a0c6691deea04d2b13a524c7e376d74ec1"
ORDER = ["05-grub.sh", "10-repo.sh", "20-cloud-init.sh", "20-update.sh", "30-ansible.sh",
         "40-addon.sh", "50-apparmor.sh", "70-system-role.sh", "80-remove-containers.sh",
         "85-admin-user.sh", "90-cleanup.sh"]


def read(path):
    with open(os.path.join(here, path)) as f:
        return f.read()


def role_script():
    files = [
        ("local.yml", "ansible/local.yml"),
        ("roles/system/defaults/main.yml", "ansible/roles/system/defaults/main.yml"),
        ("roles/system/tasks/main.yml", "ansible/roles/system/tasks/main.yml"),
        ("roles/system/templates/hardening.conf.j2", "ansible/roles/system/templates/hardening.conf.j2"),
        ("roles/system/templates/sysctl.conf.j2", "ansible/roles/system/templates/sysctl.conf.j2"),
        ("roles/system/templates/limits.conf.j2", "ansible/roles/system/templates/limits.conf.j2"),
    ]
    out = ["#!/bin/sh",
           "# Runs the baseline hardening role (ansible/roles/system) locally.",
           "# Generated by generate.py from ansible/; do not edit.",
           "set -eu",
           "export DEBIAN_FRONTEND=noninteractive",
           "WORK=/opt/imagebuilder/ansible",
           "install -d -m 0755 \"$WORK/roles/system/tasks\" \"$WORK/roles/system/defaults\" \"$WORK/roles/system/templates\""]
    for dest, src in files:
        body = read(src)
        if not body.endswith("\n"):
            body += "\n"
        out.append("cat > \"$WORK/%s\" <<'IMAGEBUILDER_ROLE_EOF'" % dest)
        out.append(body + "IMAGEBUILDER_ROLE_EOF")
    out.append("cd \"$WORK\"")
    out.append("ANSIBLE_NOCOLOR=1 ansible-playbook -i localhost, -c local local.yml")
    return "\n".join(out) + "\n"


def indent(text, n):
    pad = " " * n
    return "\n".join((pad + line) if line else "" for line in text.rstrip("\n").split("\n")) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--proxy", default="", help="optional apt proxy URL, e.g. http://proxy.example.com:3128")
    ap.add_argument("--admin-user", default="admin")
    ap.add_argument("--provider-config", default="vsphere-templates")
    ap.add_argument("--image-name", default="ubuntu-2604-vsphere-v1-0-0")
    ap.add_argument("--out", default=os.path.join(here, "40-vmimage.yaml"))
    a = ap.parse_args()
    with open(os.path.join(here, "scripts/70-system-role.sh"), "w") as f:
        f.write(role_script())
    prov = []
    for name in ORDER:
        body = read("scripts/" + name).replace("@PROXY@", a.proxy).replace("@ADMIN_USER@", a.admin_user)
        prov.append("    - type: shell\n      inline: |\n" + indent(body, 8))
    doc = f"""apiVersion: imagebuilder.io/v1alpha1
kind: VMImage
metadata:
  name: {a.image_name}
  namespace: imagebuilder-system
  labels:
    imagebuilder.io/platform: vsphere
spec:
  os:
    family: linux
    distribution: ubuntu
    version: "26.04"
    arch: amd64
  source:
    type: cloud-image
    # Canonical release-20261016; SHA256SUMS verified against the Ubuntu cloud
    # image signing key.
    url: {SOURCE_URL}
    checksum: sha256:{SOURCE_SHA256}
  provisioners:
""" + "".join(prov) + f"""  targets:
    - providerConfigRef:
        name: {a.provider_config}
      format: ova
      tags:
        managed-by: imagebuilder
  build:
    mode: remote
    timeout: 3h
"""
    with open(a.out, "w") as f:
        f.write(doc)
    print("generated", a.out)


if __name__ == "__main__":
    main()
